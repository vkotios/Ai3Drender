-- ---------------------------------------------------------------------------
-- Client review links: share a scene read-only, let clients pin notes and
-- sign off, without an account.
--
-- Grant model
-- -----------
-- Ownership so far is single-owner: every RLS policy walks a row back to
-- `projects.owner_id` via `owns_project`/`owns_asset`/`owns_scene`. That has
-- no room for "someone who isn't the owner can still see this one thing."
--
-- Rather than bolt a link-only escape hatch onto scenes, `scene_share_links`
-- is shaped as a GRANT: (resource, grantee, role, validity window). Today the
-- only resource type is a scene and the only grantee type is a bearer token,
-- but the shape is exactly what a future `project_members` table would need
-- for real team accounts - swap the token for a `grantee_user_id`, add a role
-- like 'editor', and the RLS pattern below (a SECURITY DEFINER function that
-- resolves "does the caller's identity satisfy any grant on this resource"
-- OR ownership) extends unchanged. That is deliberately as far as this goes:
-- no team-accounts table is added now, just a model that does not have to be
-- thrown away when one shows up.
--
-- Token handling
-- --------------
-- The link is a bearer credential, so only its SHA-256 hash is stored -
-- exactly like a password. The raw token is generated by the app, hashed with
-- pgcrypto's digest() before insert, and handed to the owner exactly once.
--
-- Enforcing the token in RLS
-- ---------------------------
-- These anonymous requests carry no Supabase auth session (auth.uid() is
-- null), so the token has to reach Postgres another way. PostgREST (what
-- Supabase's REST API runs on) exposes the incoming request's headers to SQL
-- as the `request.headers` GUC. The app sends the raw token as the
-- `x-scene-share-token` header on every anon-key request made from the share
-- view (see lib/supabase/server.ts's createSupabaseShareClient), and
-- `active_share_scene_id()` below reads it from there, hashes it, and checks
-- it against an unexpired, unrevoked link. That function (called over
-- supabase-js's `.rpc()`) is also how app/api/share/[token]/** resolves which
-- scene a token grants before doing anything else with it - RLS is not just a
-- backstop here, it is the actual authorization check for the whole feature.
--
-- Caveat: this project has no live Supabase instance wired into this sandbox,
-- so this header-based path could not be exercised against real PostgREST in
-- review - it follows documented PostgREST/Supabase behaviour for exposing
-- request headers as a GUC, but is only exercised end-to-end here against the
-- local-disk `Store`, where the same token/expiry/revocation checks are
-- implemented directly in `lib/db/local.ts` and `lib/share/access.ts`.
-- ---------------------------------------------------------------------------

-- Scenes: what the client sees and sets ---------------------------------------

alter table scenes
  add column if not exists client_approval text not null default 'pending'
    check (client_approval in ('pending', 'approved', 'changes_requested')),
  add column if not exists client_approval_at timestamptz,
  add column if not exists client_approval_name text,
  add column if not exists client_approval_note text;

-- Annotations: tell client notes apart from internal ones ---------------------

alter table annotations
  add column if not exists source text not null default 'internal'
    check (source in ('internal', 'client')),
  add column if not exists client_name text;

-- A client note always carries the name they typed in; an internal one never
-- does, since it is attributed to the signed-in user instead.
alter table annotations drop constraint if exists annotations_client_name_check;
alter table annotations add constraint annotations_client_name_check
  check (
    (source = 'client' and client_name is not null and length(trim(client_name)) > 0)
    or (source = 'internal' and client_name is null)
  );

-- Share links ------------------------------------------------------------------

create table if not exists scene_share_links (
  id                uuid primary key default gen_random_uuid(),
  scene_id          uuid not null references scenes (id) on delete cascade,
  -- SHA-256 hex digest of the bearer token. Never store the raw token.
  token_hash        text not null unique,
  created_by        uuid not null references auth.users (id) on delete cascade,
  -- 'commenter' is everything this feature needs today (view + pin + sign
  -- off); 'viewer' is here so a future "read-only, no pinning" link does not
  -- need a schema change.
  role              text not null default 'commenter' check (role in ('viewer', 'commenter')),
  label             text,
  expires_at        timestamptz,
  revoked_at        timestamptz,
  last_accessed_at  timestamptz,
  created_at        timestamptz not null default now()
);

create index if not exists scene_share_links_scene_idx
  on scene_share_links (scene_id, created_at desc);
-- The validity check below runs on every share-view request.
create index if not exists scene_share_links_active_idx
  on scene_share_links (token_hash) where revoked_at is null;

alter table scene_share_links enable row level security;

-- Owners manage their own scenes' links exactly like every other child table.
drop policy if exists scene_share_links_owner on scene_share_links;
create policy scene_share_links_owner on scene_share_links
  for all using (owns_scene(scene_id)) with check (owns_scene(scene_id));

-- Resolve the bearer token on the current request to the scene it grants
-- access to, or null if there is none, it is revoked, or it has expired.
-- SECURITY DEFINER: an anonymous caller has no privileges of its own to read
-- scene_share_links (RLS above only allows the owner), so this function reads
-- it on the caller's behalf after checking the hash matches.
create or replace function active_share_scene_id()
returns uuid
language sql
security definer
set search_path = public, extensions
stable
as $$
  select l.scene_id
  from scene_share_links l
  where l.token_hash = encode(
          digest(coalesce(current_setting('request.headers', true)::json->>'x-scene-share-token', ''), 'sha256'
        ), 'hex')
    and l.revoked_at is null
    and (l.expires_at is null or l.expires_at > now())
  limit 1;
$$;

grant execute on function active_share_scene_id() to anon, authenticated;

-- Best-effort "this link was opened" marker, called once per share-view load.
create or replace function touch_active_share_link()
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  update scene_share_links
  set last_accessed_at = now()
  where token_hash = encode(
          digest(coalesce(current_setting('request.headers', true)::json->>'x-scene-share-token', ''), 'sha256'
        ), 'hex')
    and revoked_at is null
    and (expires_at is null or expires_at > now());
end;
$$;

grant execute on function touch_active_share_link() to anon, authenticated;

-- Which asset versions a shared scene's staged nodes reference. The scene
-- document is JSONB, not a foreign key, so this walks the nodes array rather
-- than joining.
create or replace function shared_asset_version_ids()
returns table(id uuid)
language sql
security definer
set search_path = public
stable
as $$
  select distinct (elem->>'assetVersionId')::uuid
  from scenes s,
       jsonb_array_elements(coalesce(s.doc->'nodes', '[]'::jsonb)) as elem
  where s.id = active_share_scene_id()
    and elem->>'assetVersionId' is not null;
$$;

-- Read access for an active share link, additive to the existing owner
-- policies (RLS OR's every permissive policy on a table together).
drop policy if exists scenes_shared_read on scenes;
create policy scenes_shared_read on scenes
  for select using (id = active_share_scene_id());

drop policy if exists asset_versions_shared_read on asset_versions;
create policy asset_versions_shared_read on asset_versions
  for select using (id in (select id from shared_asset_version_ids()));

drop policy if exists annotations_shared_read on annotations;
create policy annotations_shared_read on annotations
  for select using (asset_version_id in (select id from shared_asset_version_ids()));

-- Pinning a note through the share view: only onto a piece the shared scene
-- actually stages, and only ever attributed to the client.
drop policy if exists annotations_shared_insert on annotations;
create policy annotations_shared_insert on annotations
  for insert
  with check (
    source = 'client'
    and asset_version_id in (select id from shared_asset_version_ids())
    and scene_id = active_share_scene_id()
  );

-- Setting the approval verdict: only the client_approval_* columns are meant
-- to move through this path, but RLS cannot restrict columns, only rows -
-- app/api/share/[token]/review is what actually narrows the update to those
-- fields (see NewShareLink's grant model note above re: RLS as defense in
-- depth, not the only gate).
drop policy if exists scenes_shared_review on scenes;
create policy scenes_shared_review on scenes
  for update
  using (id = active_share_scene_id())
  with check (id = active_share_scene_id());

-- Storage: only the exact mesh files the shared scene references ---------------

drop policy if exists renders_shared_read on storage.objects;
create policy renders_shared_read on storage.objects
  for select
  using (
    bucket_id = 'renders'
    and name in (
      select av.mesh_path
      from asset_versions av
      where av.id in (select id from shared_asset_version_ids())
        and av.mesh_path is not null
    )
  );
